CREATE TABLE "payouts" (
	"id" serial PRIMARY KEY NOT NULL,
	"booking_id" integer NOT NULL,
	"booking_code" text NOT NULL,
	"provider_id" integer NOT NULL,
	"provider_name" text NOT NULL,
	"visit_date" text NOT NULL,
	"total_billed_idr" integer NOT NULL,
	"service_idr" integer NOT NULL,
	"provider_share_idr" integer NOT NULL,
	"platform_fee_idr" integer NOT NULL,
	"supplies_idr" integer NOT NULL,
	"travel_idr" integer NOT NULL,
	"after_hours_idr" integer NOT NULL,
	"provider_take_idr" integer NOT NULL,
	"platform_rate" text NOT NULL,
	"status" text DEFAULT 'TERKUMPUL' NOT NULL,
	"note" text,
	"paid_at" timestamp,
	"paid_by_user_id" integer,
	"payment_reference" text,
	"created_at" timestamp DEFAULT now() NOT NULL,
	"updated_at" timestamp DEFAULT now() NOT NULL,
	CONSTRAINT "payouts_booking_id_unique" UNIQUE("booking_id")
);
